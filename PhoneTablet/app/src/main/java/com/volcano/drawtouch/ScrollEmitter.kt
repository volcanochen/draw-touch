package com.volcano.drawtouch

/**
 * 双指滚动的输出器（纯逻辑，无 Android 依赖 → 生产代码与单测共用同一份实现）。
 *
 * ## 它保证的唯一性质
 * **位移一分都不丢。**
 *
 * 每一帧的质心位移都**必定**进入死区累加器；
 * 「这一帧发不发」由累加器按**累计量**裁决，
 * **绝不**按「这一帧的位移有多大」裁决。
 *
 * ## 历史坑（2026-10-30 用户反馈）
 * 用户原话：「双指滚动内容的时候，好像过程中是有死区的，
 * 也就是**我很缓慢的滑动，累计的移动没有变成滚动**。」
 *
 * 根因：生产代码里有一道**逐帧**门限 `abs(dCx) > 0.5f`，
 * 小于它的帧被**整帧丢掉**，压根没进累加器。
 *
 * 为什么这个门限致命 —— 看本机量纲：
 *  · 触摸芯片原始值 0~4095 → **量化步长 0.377 逻辑像素**；
 *  · 慢速滑动时，一帧正好走**一个量化步**（0.377px）→ `0.377 < 0.5` → **整帧被丢**。
 *
 * 换算成速度：0.5px/帧 × 60fps = **30 逻辑像素/秒**。
 * 也就是说：**低于 30px/s 的双指滚动，位移 100% 丢失、一点都滚不动** ——
 * 用户慢慢划一段，手指走了几百像素，屏幕上纹丝不动。
 *
 * ## 语义分工（别再搞混）
 *  · 「这一帧**算不算数**」 → 永远算数（本类保证）
 *  · 「这一帧**发不发**」   → 死区累加器裁决：
 *      起手累计位移超过死区才开始输出（吃掉死区，起步不跳一大段），
 *      越过之后 **1:1 原样输出**，位移不丢。
 *
 * 「稳」和「跟得上」是两件不矛盾的事：
 * 死区只在**起手**吃掉一次，之后一路 1:1 —— 既不误触，也不吞慢速位移。
 */
class ScrollEmitter(
    /** 死区阈值（px）：起手累计位移超过它才开始输出；随设置实时变化 */
    private val thresholdProvider: () -> Float
) {

    /**
     * 死区累加器：起手吃掉一个死区，越过后 1:1 原样输出。
     * catchUp = false → 起步不会突然跳一大段（只输出「超出死区的部分」）。
     */
    private val gate = MoveDeadZone(catchUp = false) { thresholdProvider() }

    /** 手势重置：死区重新生效（新手势 / 从多指回单指 / 切换模式） */
    fun reset() {
        gate.reset()
    }

    /** 是否已经越过死区（起手吃掉的死区只吃一次） */
    fun isStarted(): Boolean = gate.isStarted()

    /**
     * 喂入一帧位移，返回真正该发给 PC 的净位移。
     *
     * @param axis 轴锁：[TwoFingerLogic.AXIS_X] 只出横向、[AXIS_Y] 只出纵向、
     *              [AXIS_FREE]（斜向）横纵同时出
     * @param dCx/dCy 本帧质心位移（px）
     */
    fun feed(axis: Int, dCx: Float, dCy: Float): DeadZoneDelta {
        // 轴锁投影：锁了单轴就把另一轴分量归零；斜向则两轴都保留。
        val dx = if (axis == TwoFingerLogic.AXIS_Y) 0f else dCx
        val dy = if (axis == TwoFingerLogic.AXIS_X) 0f else dCy
        return gate.feed(dx, dy)
    }
}
